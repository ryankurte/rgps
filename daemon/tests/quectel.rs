#[test]
fn test_quectel_decoding() {
    let mut nmea_parser = Nmea::default();

    for (i, line) in RAW_DATA
        .lines()
        .filter(|l| !l.trim().is_empty())
        .enumerate()
    {
        if let Err(e) = nmea_parser.parse(line) {
            panic!("Failed to parse line {}: {}\nError: {}", i, line, e);
        }
    }

    println!("{:#?}", nmea_parser);
}
